export function getCopernicusSentinel2Url(
  lat: number, 
  lng: number, 
  delta: number = 0.035, 
  width: number = 512, 
  height: number = 512
): string {
  const minLat = (lat - delta).toFixed(4);
  const maxLat = (lat + delta).toFixed(4);
  const minLng = (lng - delta).toFixed(4);
  const maxLng = (lng + delta).toFixed(4);
  return `https://tiles.maps.eox.at/wms?service=wms&request=getmap&version=1.3.0&layers=s2cloudless-2020&styles=&format=image/jpeg&crs=EPSG:4326&bbox=${minLat},${minLng},${maxLat},${maxLng}&width=${width}&height=${height}`;
}

export function getNasaGibsUrl(
  lat: number, 
  lng: number, 
  date: string = '2023-10-15', 
  mode: 'natural' | 'false_color' = 'natural'
): string {
  const delta = 0.08;
  const minLat = (lat - delta).toFixed(4);
  const maxLat = (lat + delta).toFixed(4);
  const minLng = (lng - delta).toFixed(4);
  const maxLng = (lng + delta).toFixed(4);
  const layer = mode === 'false_color' 
    ? 'MODIS_Terra_CorrectedReflectance_Bands721' 
    : 'MODIS_Terra_CorrectedReflectance_TrueColor';
  return `https://gibs.earthdata.nasa.gov/wms/epsg4326/best/wms.cgi?service=WMS&version=1.3.0&request=GetMap&layers=${layer}&styles=&time=${date}&format=image/jpeg&crs=CRS:84&bbox=${minLng},${minLat},${maxLng},${maxLat}&width=512&height=512`;
}

